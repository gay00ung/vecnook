#!/usr/bin/env python3
"""Generate real legacy collection bytes using an installed published CLI."""
import argparse
from pathlib import Path
import subprocess
import sys
import tempfile
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "examples/documents"))
from search import Chunk, cli, encode_document


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", required=True)
    parser.add_argument("--output", default="tests/support/legacy_v03.rs")
    parser.add_argument("--version", choices=["0.3.0-beta.2", "1.1.0"], default="0.3.0-beta.2")
    args = parser.parse_args()
    binary = Path(args.binary).resolve()
    version = subprocess.check_output([str(binary), "--version"], text=True).strip()
    if version != "vecnook " + args.version:
        raise ValueError("use the actual published " + args.version + " CLI")
    checksum = {"0.3.0-beta.2": "b1012f762776ed571ca5b492ecdb568a8652d66946e794c0c9e21a7ded03e2fd", "1.1.0": "315c6b49d90a8bfecd2bb774b05c4d8a79cf58958922720ed40648a24e389d39"}[args.version]
    with tempfile.TemporaryDirectory(prefix="vecnook-legacy-") as temporary:
        root = Path(temporary)
        space = [root, "legacy", 2, "fixture-v03:stable-model", "cosine"]
        cli(binary, "docs-init", *space)
        batch = root / "input.tsv"
        original = encode_document(2**64-1, Chunk("legacy.md", 8, 9, "original legacy 한글\n"), ["rust"])
        removed = encode_document(7, Chunk("removed.md", 1, 1, "temporary"), [])
        batch.write_text(f"put\t{2**64-1}\t1,0\t{original}\nput\t7\t0,1\t{removed}\n", encoding="utf-8")
        cli(binary, "docs-batch", *space, batch)
        cli(binary, "docs-checkpoint", *space)
        updated = encode_document(2**64-1, Chunk("legacy.md", 8, 9, "updated legacy 원문\n\r\n"), ["rust"])
        batch.write_text(f"put\t{2**64-1}\t0,1\t{updated}\ndelete\t7\n", encoding="utf-8")
        cli(binary, "docs-batch", *space, batch)
        if args.version == "1.1.0":
            # Old snapshots retain superseded/deleted payloads. Leave a fresh WAL update
            # after that snapshot to cover both reading paths in the next minor release.
            cli(binary, "docs-checkpoint", *space)
            cli(binary, "docs-batch", *space, batch)
        lines = [f"// Generated by tools/generate_legacy_fixture.py using published vecnook {args.version}.",
                 f"// Registry source checksum: {checksum}.",
                 "// Authored text; committed snapshot/cache plus a later update/delete WAL."]
        for name in ["snapshot.bin", "wal.bin", "index.bin", "collection.bin"]:
            values = list((root / "legacy" / name).read_bytes())
            constant = name.split(".")[0].upper()
            lines.append(f"pub const {constant}: &[u8] = &[")
            lines.extend("    " + ", ".join(map(str, values[i:i+16])) + "," for i in range(0,len(values),16))
            lines.append("];")
        Path(args.output).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"Generated real {args.version} snapshot/WAL/cache/collection upgrade fixture")


if __name__ == "__main__":
    main()
